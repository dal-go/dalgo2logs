// These byte fixtures were generated by the pre-change marshalEntry at 967b108.
// They pin evidence representation and therefore the canonical source references.
func TestMarshalEntryPreservesExistingBytesAndHashes(t *testing.T) {
	expected := map[string]string{
		"empty":       `{"Timestamp":"0001-01-01T00:00:00Z","Severity":0,"Payload":null,"Labels":null,"InsertID":"","HTTPRequest":null,"Operation":null,"LogName":"","Resource":null,"Trace":"","SpanID":"","TraceSampled":false,"SourceLocation":null}`,
		"full":        `{"Timestamp":"2026-10-21T08:30:00.123456789Z","Severity":400,"Payload":{"message":"request failed","number":9007199254740993},"Labels":{"service":"orders"},"InsertID":"insert-1","HTTPRequest":null,"Operation":{"id":"op-1","producer":"worker","first":true,"last":true},"LogName":"projects/demo/logs/orders","Resource":{"type":"service","labels":{"service_name":"orders"}},"Trace":"projects/demo/traces/trace-1","SpanID":"span-1","TraceSampled":true,"SourceLocation":{"file":"worker.go","line":42,"function":"process"}}`,
		"nil_request": `{"Timestamp":"2026-10-21T08:30:00.123456789Z","Severity":400,"Payload":{"message":"request failed","number":9007199254740993},"Labels":{"service":"orders"},"InsertID":"insert-1","HTTPRequest":{"Request":null,"RequestSize":123,"Status":503,"ResponseSize":456,"Latency":250000000,"LocalIP":"127.0.0.1","RemoteIP":"192.0.2.1","CacheHit":true,"CacheValidatedWithOriginServer":true,"CacheFillBytes":789,"CacheLookup":true},"Operation":{"id":"op-1","producer":"worker","first":true,"last":true},"LogName":"projects/demo/logs/orders","Resource":{"type":"service","labels":{"service_name":"orders"}},"Trace":"projects/demo/traces/trace-1","SpanID":"span-1","TraceSampled":true,"SourceLocation":{"file":"worker.go","line":42,"function":"process"}}`,
		"request":     `{"Timestamp":"2026-10-21T08:30:00.123456789Z","Severity":400,"Payload":{"message":"request failed","number":9007199254740993},"Labels":{"service":"orders"},"InsertID":"insert-1","HTTPRequest":{"Method":"POST","URL":"https://example.test/orders?id=11045","Proto":"HTTP/2.0","Header":{"Content-Type":["application/json"],"X-Evidence":["a","b"]},"RequestSize":123,"Status":503,"ResponseSize":456,"Latency":"250ms","LocalIP":"127.0.0.1","RemoteIP":"192.0.2.1","CacheHit":true,"CacheValidatedWithOriginServer":true,"CacheFillBytes":789,"CacheLookup":true},"Operation":{"id":"op-1","producer":"worker","first":true,"last":true},"LogName":"projects/demo/logs/orders","Resource":{"type":"service","labels":{"service_name":"orders"}},"Trace":"projects/demo/traces/trace-1","SpanID":"span-1","TraceSampled":true,"SourceLocation":{"file":"worker.go","line":42,"function":"process"}}`,
	}
	cases := map[string]*logging.Entry{"empty": {}, "full": serializationFixture(), "nil_request": serializationFixture(), "request": serializationFixture()}
	cases["full"].HTTPRequest = nil
	cases["nil_request"].HTTPRequest.Request = nil
	for name, entry := range cases {
		t.Run(name, func(t *testing.T) {
			raw, err := marshalEntry(entry)
			if err != nil || string(raw) != expected[name] {
				t.Fatalf("canonical bytes changed:\n got: %s\nwant: %s\nerror: %v", raw, expected[name], err)
			}
			row, err := mapEntry(entry, "demo-project")
			if err != nil {
				t.Fatal(err)
			}
			digest := sha256.Sum256([]byte("demo-project\x00" + expected[name]))
			if row["raw"] != expected[name] || row["source_ref"] != "gcl:"+hex.EncodeToString(digest[:]) {
				t.Fatalf("canonical evidence/reference changed: %#v", row)
			}
			payload, err := json.Marshal(entry.Payload)
			if err != nil || row["fields_json"] != string(payload) {
				t.Fatalf("payload evidence changed: %#v, %v", row, err)
			}
		})
	}
}

func TestMarshalEntryPropagatesUnsupportedPayloadAndMalformedRequest(t *testing.T) {
	for _, withRequest := range []bool{false, true} {
		entry := serializationFixture()
		if !withRequest {
			entry.HTTPRequest = nil
		}
		entry.Payload = make(chan int)
		if _, err := marshalEntry(entry); err == nil {
			t.Fatal("unsupported payload became valid evidence")
		}
	}
	entry := serializationFixture()
	entry.HTTPRequest.Request.URL = nil
	if _, err := marshalEntry(entry); err == nil {
		t.Fatal("malformed request became valid evidence")
	}
	entry.Timestamp = time.Date(2026, 10, 19, 3, 30, 0, 0, time.UTC)
	db := &database{cfg: Config{Collection: "entries", ProjectID: "demo-project", MaxResults: 20, MaxWindow: time.Hour, MaxQueryDuration: time.Second}, entries: func(context.Context, string, int) entryReader { return &fakeReader{entries: []*logging.Entry{entry}} }}
	if _, err := db.ExecuteQueryToRecordsReader(context.Background(), boundedQuery()); err == nil || !strings.Contains(err.Error(), "entry cannot be encoded") || strings.Contains(err.Error(), "URL") {
		t.Fatalf("reader must report sanitized serialization failure: %v", err)
	}
}
